#!/usr/bin/env node
/*
 * Generates src/builder/query/sql/druidSqlDocs.ts from the Apache Druid SQL
 * documentation markdown, pinned to the DRUID_VERSION in .env.
 *
 * Ported from Apache Druid's web-console/script/create-sql-docs.mjs
 * (https://github.com/apache/druid, Apache License 2.0). Differences:
 *   - fetches the docs over the network at the pinned tag (no local checkout),
 *   - keeps descriptions as Markdown instead of converting to HTML,
 *   - emits plain TS object literals plus a DRUID_DOCS_VERSION constant.
 *
 * Usage: yarn generate:sql-docs   (requires network access)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { parseDruidSqlDocs } = require('./druidSqlDocsParser.js');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const ENV_FILE = path.join(REPO_ROOT, '.env');
const OUTPUT_FILE = path.join(REPO_ROOT, 'src', 'builder', 'query', 'sql', 'druidSqlDocs.ts');

const DOC_FILES = [
  'sql-data-types.md',
  'sql-scalar.md',
  'sql-aggregations.md',
  'sql-array-functions.md',
  'sql-multivalue-string-functions.md',
  'sql-json-functions.md',
  'sql-window-functions.md',
  'sql-operators.md',
];

const MINIMUM_EXPECTED_NUMBER_OF_FUNCTIONS = 150;
const MINIMUM_EXPECTED_NUMBER_OF_DATA_TYPES = 15;

// Entries the markdown tables do not contain (upstream hand-seeds these too).
const SEEDED_FUNCTIONS = {
  TABLE: { args: 'external', description: 'Defines a logical table from an external.' },
  EXTERN: { args: 'inputSource, inputFormat, rowSignature?', description: 'Reads external data.' },
  TYPE: {
    args: 'nativeType',
    description:
      'A purely type system modification function what wraps a Druid native type to make it into a SQL type.',
  },
  UNNEST: {
    args: 'arrayExpression',
    description:
      "Unnests ARRAY typed values. The source for UNNEST can be an array type column, or an input that's been transformed into an array, such as with helper functions like `MV_TO_ARRAY` or `ARRAY`.",
  },
  PI: { args: '', description: 'Returns the value of pi.' },
};

function readDruidVersion() {
  const env = fs.readFileSync(ENV_FILE, 'utf-8');
  const m = env.match(/^DRUID_VERSION="?([^"\n]+)"?$/m);
  if (!m) {
    throw new Error('Could not find DRUID_VERSION in .env — cannot pin the docs tag.');
  }
  return m[1].trim();
}

async function fetchDoc(version, file) {
  const url = `https://raw.githubusercontent.com/apache/druid/druid-${version}/docs/querying/${file}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  }
  return res.text();
}

function sortedObject(obj) {
  return Object.fromEntries(Object.entries(obj).sort(([a], [b]) => a.localeCompare(b)));
}

async function main() {
  const version = readDruidVersion();
  console.log(`Generating Druid SQL docs catalog for Druid ${version} ...`);

  const contents = await Promise.all(DOC_FILES.map((f) => fetchDoc(version, f)));
  const { functions, dataTypes } = parseDruidSqlDocs(contents.join('\n'));

  const allFunctions = sortedObject({ ...SEEDED_FUNCTIONS, ...functions });
  const allDataTypes = sortedObject(dataTypes);

  const numFunctions = Object.keys(allFunctions).length;
  const numDataTypes = Object.keys(allDataTypes).length;
  if (numFunctions < MINIMUM_EXPECTED_NUMBER_OF_FUNCTIONS) {
    throw new Error(
      `Only found ${numFunctions} functions (expected >= ${MINIMUM_EXPECTED_NUMBER_OF_FUNCTIONS}). Did the Druid docs format change?`
    );
  }
  if (numDataTypes < MINIMUM_EXPECTED_NUMBER_OF_DATA_TYPES) {
    throw new Error(
      `Only found ${numDataTypes} data types (expected >= ${MINIMUM_EXPECTED_NUMBER_OF_DATA_TYPES}). Did the Druid docs format change?`
    );
  }

  const content = `// GENERATED by scripts/generate-druid-sql-docs.mjs from Apache Druid ${version} docs (Apache-2.0).
// Do not edit by hand — re-run \`yarn generate:sql-docs\`.
/* eslint-disable */
export const DRUID_DOCS_VERSION = '${version}'; // = DRUID_VERSION from .env at generation time

export interface SqlFunctionDoc {
  args: string;
  description: string;
}

export interface SqlDataTypeDoc {
  runtime: string;
  description: string;
}

export const SQL_FUNCTIONS: Record<string, SqlFunctionDoc> = ${JSON.stringify(allFunctions, null, 2)};

export const SQL_DATA_TYPES: Record<string, SqlDataTypeDoc> = ${JSON.stringify(allDataTypes, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
  console.log(
    `Wrote ${numFunctions} functions and ${numDataTypes} data types to ${path.relative(REPO_ROOT, OUTPUT_FILE)}`
  );
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
